CREATE TABLE IF NOT EXISTS public.users (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT users_username_not_blank
        CHECK (LENGTH(TRIM(username)) > 0)
);

CREATE TABLE IF NOT EXISTS public.workouts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    workout_date DATE NOT NULL,
    body_part TEXT NOT NULL,
    exercise_name TEXT NOT NULL,
    sets INTEGER NOT NULL,
    reps INTEGER NOT NULL,
    weight NUMERIC(7, 2) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT workouts_body_part_check
        CHECK (body_part IN ('chest', 'shoulder', 'arm', 'leg', 'core', 'back')),
    CONSTRAINT workouts_exercise_name_not_blank
        CHECK (LENGTH(TRIM(exercise_name)) > 0),
    CONSTRAINT workouts_sets_positive
        CHECK (sets > 0),
    CONSTRAINT workouts_reps_positive
        CHECK (reps > 0),
    CONSTRAINT workouts_weight_range
        CHECK (weight >= 0 AND weight <= 99999.99)
);

CREATE TABLE IF NOT EXISTS public.posts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    visibility TEXT NOT NULL DEFAULT 'public',
    image_url TEXT,
    image_path TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT posts_content_not_blank
        CHECK (LENGTH(TRIM(content)) > 0),
    CONSTRAINT posts_visibility_check
        CHECK (visibility IN ('public', 'friends-only'))
);

CREATE TABLE IF NOT EXISTS public.friendships (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    receiver_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT friendships_users_different
        CHECK (requester_id <> receiver_id),
    CONSTRAINT friendships_status_check
        CHECK (status IN ('pending', 'accepted'))
);

CREATE INDEX IF NOT EXISTS workouts_user_date_idx
    ON public.workouts (user_id, workout_date DESC);

CREATE INDEX IF NOT EXISTS posts_created_at_idx
    ON public.posts (created_at DESC);

CREATE INDEX IF NOT EXISTS posts_author_idx
    ON public.posts (author_id);

CREATE INDEX IF NOT EXISTS friendships_requester_status_idx
    ON public.friendships (requester_id, status);

CREATE INDEX IF NOT EXISTS friendships_receiver_status_idx
    ON public.friendships (receiver_id, status);

CREATE UNIQUE INDEX IF NOT EXISTS friendships_unique_pair_idx
    ON public.friendships (
        LEAST(requester_id, receiver_id),
        GREATEST(requester_id, receiver_id)
    );

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workouts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.friendships ENABLE ROW LEVEL SECURITY;

